#!/usr/bin/env bash
# Regenerate mame-chd-src/: the subset of MAME's source tree that build.rs
# compiles, plus the headers and licenses it needs. The result is
# committed and shipped in the crates.io package, so source builds work
# offline (e.g. distro packaging via `cargo vendor`) without the full
# ~900 MB MAME checkout.
#
# Usage: scripts/vendor-mame.sh [path-to-mame-checkout]
#
# The MAME checkout defaults to the deps/mame submodule. Its version must
# match the crate version (crate 0.289.x <-> MAME 0.289); set
# ALLOW_VERSION_MISMATCH=1 to vendor anyway.
#
# Source files are taken from build.rs itself (every "mame-chd-src/...c"
# or ".cpp" string literal), so adding a file to build.rs and re-running
# this script is all a new source file needs. Headers are copied by
# directory, below.

set -euo pipefail

repo=$(cd "$(dirname "$0")/.." && pwd)
src=$(cd "${1:-$repo/deps/mame}" && pwd)
dst=$repo/mame-chd-src

if [ ! -f "$src/src/lib/util/chd.cpp" ] || [ ! -f "$src/makefile" ]; then
    echo "error: $src does not look like a MAME source tree" >&2
    echo "       (run 'git submodule update --init deps/mame' or pass a path)" >&2
    exit 1
fi

# --- Version -------------------------------------------------------------

mame_version=$(sed -n 's/.*BARE_BUILD_VERSION "\([0-9.]*\)".*/\1/p' "$src/makefile" | head -n 1)
if [ -z "$mame_version" ]; then
    echo "error: could not read BARE_BUILD_VERSION from $src/makefile" >&2
    exit 1
fi

crate_version=$(sed -n 's/^version = "\(.*\)"/\1/p' "$repo/Cargo.toml" | head -n 1)
expected_mame=${crate_version%.*}
if [ "$mame_version" != "$expected_mame" ]; then
    if [ "${ALLOW_VERSION_MISMATCH:-}" = "1" ]; then
        echo "warning: MAME $mame_version does not match crate $crate_version (expected MAME $expected_mame)" >&2
    else
        echo "error: MAME $mame_version does not match crate $crate_version (expected MAME $expected_mame)" >&2
        echo "       check out the matching MAME tag or set ALLOW_VERSION_MISMATCH=1" >&2
        exit 1
    fi
fi

if git -C "$src" rev-parse --git-dir >/dev/null 2>&1; then
    mame_commit=$(git -C "$src" rev-parse HEAD)
    mame_tag=$(git -C "$src" describe --tags --exact-match 2>/dev/null || echo "none")
    if [ -n "$(git -C "$src" status --porcelain --untracked-files=no)" ]; then
        echo "warning: $src has uncommitted changes; vendoring them as-is" >&2
        mame_commit="$mame_commit-dirty"
    fi
else
    mame_commit=unknown
    mame_tag=unknown
fi

# --- File list -----------------------------------------------------------

# Sources compiled by build.rs.
sources=$(grep -oE '"mame-chd-src/[^"]+\.(c|cpp)"' "$repo/build.rs" | tr -d '"' | sed 's#^mame-chd-src/##' | sort -u)
if [ -z "$sources" ]; then
    echo "error: found no mame-chd-src/ sources in build.rs" >&2
    exit 1
fi

# Directories whose headers are copied (non-recursive).
header_dirs="
src/lib/util
src/osd
3rdparty/zlib
3rdparty/lzma/C
3rdparty/utf8proc
3rdparty/zstd/lib
3rdparty/zstd/lib/common
3rdparty/zstd/lib/compress
3rdparty/zstd/lib/decompress
3rdparty/flac/include/FLAC
3rdparty/flac/include/share
3rdparty/flac/src/libFLAC/include
3rdparty/flac/src/libFLAC/include/private
3rdparty/flac/src/libFLAC/include/protected
"

# Files pulled in with #include rather than compiled on their own.
extra_files="
3rdparty/utf8proc/utf8proc_data.c
$(cd "$src" && ls 3rdparty/flac/src/libFLAC/deduplication/*.c)
"

licenses="
COPYING
docs/legal/BSD-3-Clause
3rdparty/zlib/LICENSE
3rdparty/lzma/DOC/lzma-sdk.txt
3rdparty/zstd/LICENSE
3rdparty/zstd/COPYING
3rdparty/utf8proc/LICENSE.md
3rdparty/flac/COPYING.Xiph
"

# --- Copy ----------------------------------------------------------------

rm -rf "$dst"
mkdir -p "$dst"

copy() {
    if [ ! -f "$src/$1" ]; then
        echo "error: missing $src/$1" >&2
        exit 1
    fi
    mkdir -p "$dst/$(dirname "$1")"
    cp "$src/$1" "$dst/$1"
}

for f in $sources $extra_files $licenses; do
    copy "$f"
done

for d in $header_dirs; do
    if [ ! -d "$src/$d" ]; then
        echo "error: missing directory $src/$d" >&2
        exit 1
    fi
    for f in "$src/$d"/*.h "$src/$d"/*.hpp "$src/$d"/*.ipp; do
        [ -f "$f" ] && copy "${f#"$src"/}"
    done
done

cat > "$dst/MAME_VERSION" <<EOF
# Generated by scripts/vendor-mame.sh; do not edit.
version=$mame_version
tag=$mame_tag
commit=$mame_commit
upstream=https://github.com/mamedev/mame
EOF

cat > "$dst/README.md" <<EOF
# mame-chd-src

The subset of [MAME](https://github.com/mamedev/mame)'s source tree that
libchdman-rs compiles: the CHD core from \`src/lib/util\` plus the bundled
zlib, LZMA SDK, zstd, FLAC and utf8proc from \`3rdparty\`. Files are
unmodified copies at their upstream paths; licenses are included at their
upstream paths too.

The exact upstream version is recorded in \`MAME_VERSION\`. Do not edit
these files by hand. To regenerate:

    scripts/vendor-mame.sh [path-to-mame-checkout]
EOF

count=$(find "$dst" -type f | wc -l | tr -d ' ')
size=$(du -sh "$dst" | cut -f1)
echo "Vendored MAME $mame_version ($mame_tag, $mame_commit): $count files, $size -> mame-chd-src/"
